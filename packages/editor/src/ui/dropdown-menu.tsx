// NOTE: Never stop propagation of onPointerDown in the content level as it interrupts radix's pointer related
// dismissal logic
function DropdownMenuContent({
  className,
  sideOffset = 4,
  onTouchMove,
  onWheel,
  portalContainer,
  ...props
}: React.ComponentProps<typeof DropdownMenuPrimitive.Content> & {
  portalContainer?: React.ComponentProps<
    typeof DropdownMenuPrimitive.Portal
  >["container"];
}) {
  return (
    <DropdownMenuPrimitive.Portal container={portalContainer}>
      <DropdownMenuPrimitive.Content
        data-slot="dropdown-menu-content"
        sideOffset={sideOffset}
        className={cn(
          "pointer-events-auto bg-popover text-popover-foreground z-[70] min-w-32 overflow-hidden rounded-xl border p-1.5 shadow-lg",
          "max-h-(--radix-dropdown-menu-content-available-height) origin-(--radix-dropdown-menu-content-transform-origin) overflow-x-hidden overflow-y-auto",
          "data-[state=open]:animate-in data-[state=closed]:animate-out data-[state=closed]:fade-out-0 data-[state=open]:fade-in-0 data-[state=closed]:zoom-out-95 data-[state=open]:zoom-in-95 data-[side=bottom]:slide-in-from-top-2 data-[side=left]:slide-in-from-right-2 data-[side=right]:slide-in-from-left-2 data-[side=top]:slide-in-from-bottom-2",
          className,
        )}
        // Fixes the issue of scroll not working for the content given a fixed height when used on a dialog
        onWheel={(event) => {
          event.stopPropagation();
          onWheel?.(event);
        }}
        onTouchMove={(event) => {
          event.stopPropagation();
          onTouchMove?.(event);
        }}
        {...props}
      />
    </DropdownMenuPrimitive.Portal>
  );
}

